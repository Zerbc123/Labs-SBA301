package vn.edu.fpt.services;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;
import vn.edu.fpt.entity.Category;
import vn.edu.fpt.repositories.ICategoryRepository;
import vn.edu.fpt.repositories.INewsArticleRepository;

import java.util.List;

@Service
public class CategoryService implements ICategoryService {

    @Autowired
    private ICategoryRepository categoryRepository;

    @Autowired
    private INewsArticleRepository newsArticleRepository;

    @Override
    public List<Category> getAllCategories() {
        return categoryRepository.findAll();
    }

    @Override
    public List<Category> getActiveCategories() {
        return categoryRepository.findByIsActiveTrue();
    }

    @Override
    public Category getCategoryById(Short id) {
        return categoryRepository.findById(id)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Category not found with ID: " + id));
    }

    @Override
    public Category createCategory(Category category) {
        if (category.getCategoryName() == null || category.getCategoryName().trim().isEmpty()) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Category Name is required!");
        }
        category.setCategoryID(null); // Auto-generated by SQL Server IDENTITY
        if (category.getIsActive() == null) {
            category.setIsActive(true);
        }
        return categoryRepository.save(category);
    }

    @Override
    public Category updateCategory(Short id, Category category) {
        Category existing = getCategoryById(id);
        if (category.getCategoryName() != null) {
            existing.setCategoryName(category.getCategoryName());
        }
        if (category.getCategoryDesciption() != null) {
            existing.setCategoryDesciption(category.getCategoryDesciption());
        }
        if (category.getParentCategoryID() != null) {
            existing.setParentCategoryID(category.getParentCategoryID());
        }
        if (category.getIsActive() != null) {
            existing.setIsActive(category.getIsActive());
        }
        return categoryRepository.save(existing);
    }

    @Override
    public void deleteCategory(Short id) {
        if (!categoryRepository.existsById(id)) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Category not found with ID: " + id);
        }
        // Business Rule: Cannot delete category if any news article belongs to it
        if (newsArticleRepository.existsByCategory_CategoryID(id)) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Cannot delete category because it is already used in news articles!");
        }
        categoryRepository.deleteById(id);
    }

    @Override
    public List<Category> searchCategories(String keyword) {
        if (keyword == null || keyword.trim().isEmpty()) {
            return categoryRepository.findAll();
        }
        return categoryRepository.findByCategoryNameContainingIgnoreCase(keyword.trim());
    }
}
